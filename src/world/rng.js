/**
 * rng.js — 고정 시드 난수.
 *
 * **매 판 같은 자리에 같은 것이 나와야 한다.** 레벨이 판마다 흔들리면 난이도를
 * 조율할 수가 없고, 지오메트리 지문 검사(`tools/qa_geometry.mjs`)도 성립하지 않는다.
 * 그래서 구역 배치·잔해 산포에는 `Math.random()` 을 쓰지 않는다.
 * (연출용 흔들림 — 불꽃 방향, 비상등 깜빡임 — 은 매번 달라야 하므로 그쪽은 그대로 쓴다.)
 *
 * 알고리즘은 **선형 합동법**(Numerical Recipes 계수)이다. 품질보다 두 가지가 중요하다.
 *   · 상태가 32비트 정수 하나뿐이라 값싸고, 시드만 알면 언제든 같은 수열이 나온다
 *   · 구현이 짧아서 **여기저기 베껴 쓰기 쉬웠다** — 실제로 여섯 파일에 같은 식이
 *     복사돼 있었다. 한 곳이 틀어져도 아무도 모르는 상태라 여기로 모았다.
 *
 * 수열을 바꾸면 다섯 구역의 배치가 전부 달라진다. 계수·나눗수를 건드리지 마라.
 */

/** @param {number} seed 32비트로 잘린다. 구역마다 다른 값을 준다 */
export function makeRng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;      // [0, 1)
  };
}
